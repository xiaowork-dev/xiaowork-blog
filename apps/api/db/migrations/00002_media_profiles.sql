CREATE TABLE media_assets (
    id                uuid         PRIMARY KEY,
    uploaded_by       uuid         NOT NULL REFERENCES users (id),
    usage_kind        varchar(20)  NOT NULL,
    storage_key       text         NOT NULL,
    original_filename varchar(255) NOT NULL,
    mime_type         varchar(40)  NOT NULL,
    size_bytes        bigint       NOT NULL,
    width             integer      NOT NULL,
    height            integer      NOT NULL,
    sha256            bytea,
    state             varchar(20)  NOT NULL DEFAULT 'READY',
    created_at        timestamptz  NOT NULL DEFAULT now(),
    deleted_at        timestamptz,
    CONSTRAINT media_assets_storage_key_key UNIQUE (storage_key),
    CONSTRAINT media_assets_usage_kind_check CHECK (usage_kind IN ('ARTICLE', 'AVATAR', 'SITE', 'PAGE')),
    -- Private relative key generated by the backend: no absolute paths, backslashes or parent traversal.
    CONSTRAINT media_assets_storage_key_safe CHECK (
        storage_key <> '' AND storage_key !~ '^/' AND storage_key !~ '\\' AND storage_key !~ '(^|/)\.\.(/|$)'
    ),
    CONSTRAINT media_assets_mime_type_check CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp', 'image/gif')),
    CONSTRAINT media_assets_size_positive CHECK (size_bytes > 0),
    CONSTRAINT media_assets_dimensions_positive CHECK (width > 0 AND height > 0),
    CONSTRAINT media_assets_sha256_len CHECK (sha256 IS NULL OR octet_length(sha256) = 32),
    CONSTRAINT media_assets_state_check CHECK (state IN ('READY', 'PENDING_DELETE', 'DELETED')),
    CONSTRAINT media_assets_deleted_at_check CHECK ((state = 'DELETED') = (deleted_at IS NOT NULL))
);
CREATE INDEX media_assets_uploader_created_idx ON media_assets (uploaded_by, created_at DESC);

CREATE TABLE user_profiles (
    user_id         uuid         PRIMARY KEY REFERENCES users (id),
    avatar_media_id uuid         REFERENCES media_assets (id),
    bio             varchar(200),
    updated_at      timestamptz  NOT NULL DEFAULT now()
);
-- Reverse lookup for "is this media referenced?" checks.
CREATE INDEX user_profiles_avatar_media_idx ON user_profiles (avatar_media_id) WHERE avatar_media_id IS NOT NULL;

